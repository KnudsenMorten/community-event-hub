namespace CommunityHub.Core.Domain.Evaluation;

/// <summary>
/// §747 C8 — a SERVICE credential: an external system authorised to pull generated PDF reports.
/// </summary>
/// <remarks>
/// <para>The brief's access-control table names exactly one consumer type for the outbound report
/// pull — <i>"Service credential for external systems"</i>. That is deliberately neither a CEH login
/// nor a device key: the caller is a program with no browser to be redirected to, and no physical
/// unit to be paired.</para>
///
/// <para>🔒 <b>This reuses the device credential mechanism rather than inventing a third scheme.</b>
/// The key is generated by <see cref="Evaluation.EvaluationIngestService.NewKey"/>, stored only as
/// a PBKDF2 <c>salt:hash</c>, and verified by the same constant-time comparison. There is now one
/// way to hold a machine credential in this system, not two that drift apart.</para>
///
/// <para>🔒 <b>Two keys, for the same reason the devices have two.</b> A consumer cannot usually be
/// updated at the same instant we rotate — it may be a scheduled job in someone else's
/// infrastructure. <see cref="PreviousKeyHash"/> keeps the old key working until the other side has
/// switched, so rotating a credential never means an outage we have to co-ordinate by e-mail.</para>
///
/// <para>🔒 <b>Scoped to ONE event.</b> The brief's rule is that organiser access is authorised per
/// event even while there is only one — <i>"this is the same constraint that keeps the ELDK27
/// extraction viable"</i>. A credential therefore names its event, and a request for any other
/// event's report is refused even with a valid key.</para>
///
/// <para>⚠️ <b>This row grants access to session reports, which quote verbatim attendee comments.</b>
/// That is the most sensitive data in the system. Issue narrowly, and prefer
/// <see cref="IsActive"/> = false over deleting, so an audit still shows the credential existed.</para>
/// </remarks>
public class EvaluationApiClient
{
    public int Id { get; set; }

    /// <summary>The edition this credential may read. A key is never valid across events.</summary>
    public int EventId { get; set; }
    public Event Event { get; set; } = null!;

    /// <summary>
    /// Who this credential was issued to ("Vendor report sync"). Human-facing only — never matched,
    /// never parsed, and never part of authentication.
    /// </summary>
    public string Name { get; set; } = string.Empty;

    /// <summary>
    /// PBKDF2 <c>salt:hash</c> of the issued key — never the key itself, so a database leak yields
    /// no working credential. Identical treatment to
    /// <see cref="EvaluationDevice.KeyHash"/> and to a login PIN.
    /// </summary>
    public string KeyHash { get; set; } = string.Empty;

    /// <summary>The PREVIOUS key, still accepted while the consumer switches over. Null when unused.</summary>
    public string? PreviousKeyHash { get; set; }

    /// <summary>
    /// Revocation without a deploy: false ⇒ every request presenting this key is refused. A consumer
    /// that has been decommissioned, or a key believed leaked, is disabled here.
    /// </summary>
    public bool IsActive { get; set; } = true;

    /// <summary>
    /// Last successful authentication. 🔑 The only way to answer "is anything still using this?"
    /// before revoking it, and the signal that a consumer has silently stopped polling.
    /// </summary>
    public DateTimeOffset? LastUsedAt { get; set; }

    public DateTimeOffset CreatedAt { get; set; }
    public DateTimeOffset UpdatedAt { get; set; }
}
