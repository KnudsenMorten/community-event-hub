    /// <summary>
    /// §1354 — the edition's DEFAULT policy for one channel (<paramref name="channel"/> = "kiosk" or "qr").
    /// Rating only on the kiosk is §1353's one-tap mode (*"easily and quickly turn off the wider context
    /// capture if people queue up"*). Tablets pick it up with their next session refresh (≤ 60 s).
    /// </summary>
    public async Task<IActionResult> OnPostSetDefaultPolicyAsync(string? channel, int policy, CancellationToken ct)
    {
        var me = _participant.Current;
        if (me is null) return RedirectToPage("/Login");
        if (!OrganizerAuth.IsRealOrganizer(me)) return Forbid();

        var ev = await _db.Events.FirstOrDefaultAsync(e => e.Id == me.EventId, ct);
        var kiosk = string.Equals(channel, "kiosk", StringComparison.OrdinalIgnoreCase);
        var qr = string.Equals(channel, "qr", StringComparison.OrdinalIgnoreCase);
        var chosen = (FeedbackCapturePolicy)policy;
        if (ev is not null && FeedbackCapturePolicies.IsDefined(policy)
            && ((kiosk && FeedbackCapturePolicies.KioskChoices.Contains(chosen))
                || (qr && FeedbackCapturePolicies.QrChoices.Contains(chosen))))
        {
            if (kiosk) ev.KioskCapturePolicy = chosen; else ev.QrCapturePolicy = chosen;
            await _db.SaveChangesAsync(ct);
            Message = kiosk
                ? $"Default kiosk policy: {FeedbackCapturePolicies.Label(chosen)}. Tablets without their own policy switch within a minute."
                : $"Default QR policy: {FeedbackCapturePolicies.Label(chosen)}. Rooms without their own QR policy use it from the next scan.";
        }

        await LoadAsync(me.EventId, ct);
        return Page();
    }

