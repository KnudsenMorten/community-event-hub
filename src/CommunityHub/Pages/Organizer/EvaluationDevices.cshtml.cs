    /// <summary>
    /// Register one or many devices. The textarea takes ONE IDENTIFIER PER LINE so the 25 units can
    /// be entered in a single pass — reading them off enclosures one form at a time is how a
    /// pre-event task gets abandoned half-done.
    /// </summary>
    public async Task<IActionResult> OnPostAddAsync(string? identifiers, string? label, CancellationToken ct)
    {
        var me = _participant.Current;
        if (me is null) return RedirectToPage("/Login");
        if (!OrganizerAuth.IsRealOrganizer(me)) return Forbid();

        var ids = (identifiers ?? string.Empty)
            .Split(new[] { '\n', '\r', ',', ';' }, StringSplitOptions.RemoveEmptyEntries)
            .Select(s => s.Trim())
            .Where(s => s.Length > 0)
            .Distinct(StringComparer.Ordinal)
            .ToList();

        if (ids.Count == 0)
        {
            Message = "Enter at least one device identifier.";
            await LoadAsync(me.EventId, ct);
            return Page();
        }

        var existing = await _db.EvaluationDevices
            .Where(d => d.EventId == me.EventId)
            .Select(d => d.SerialNumber)
            .ToListAsync(ct);
        var existingSet = existing.ToHashSet(StringComparer.Ordinal);

        var now = _clock.GetUtcNow();
        var issued = new List<(string, string)>();
        var skipped = 0;

        foreach (var id in ids)
        {
            // Re-adding an identifier must NOT silently issue a second key for a unit that is
            // already in the field — that would look like it worked and leave the device on a key
            // we no longer consider current.
            if (existingSet.Contains(id)) { skipped++; continue; }

            var key = EvaluationIngestService.NewKey();
            _db.EvaluationDevices.Add(new EvaluationDevice
            {
                EventId = me.EventId,
                SerialNumber = id,
                KeyHash = EvaluationIngestService.HashKey(key),
                Label = string.IsNullOrWhiteSpace(label) ? null : label.Trim(),
                IsActive = true,
                CreatedAt = now,
                UpdatedAt = now,
            });
            issued.Add((id, key));
        }

        await _db.SaveChangesAsync(ct);

        IssuedKeys = issued;
        Message = issued.Count == 0
            ? $"Nothing added — all {skipped} identifier(s) are already registered."
            : $"Registered {issued.Count} device(s)"
              + (skipped > 0 ? $"; skipped {skipped} already registered." : ".")
              + " Copy the keys below now — they cannot be shown again.";

        await LoadAsync(me.EventId, ct);
        return Page();
    }

    /// <summary>
    /// Rotate a device's key. The OLD key keeps working (it moves to
    /// <see cref="EvaluationDevice.PreviousKeyHash"/>) so a staggered OTA rollout cannot brick a
    /// unit that has not updated yet.
    /// </summary>
    public async Task<IActionResult> OnPostRotateAsync(int id, CancellationToken ct)
    {
        var me = _participant.Current;
        if (me is null) return RedirectToPage("/Login");
        if (!OrganizerAuth.IsRealOrganizer(me)) return Forbid();

        var device = await _db.EvaluationDevices
            .FirstOrDefaultAsync(d => d.Id == id && d.EventId == me.EventId, ct);
        if (device is null) { Message = "That device no longer exists."; await LoadAsync(me.EventId, ct); return Page(); }

        var key = EvaluationIngestService.NewKey();
        device.PreviousKeyHash = device.KeyHash;
        device.KeyHash = EvaluationIngestService.HashKey(key);
        device.UpdatedAt = _clock.GetUtcNow();
        await _db.SaveChangesAsync(ct);

        IssuedKeys = new[] { (device.SerialNumber, key) };
        Message = $"New key issued for {device.SerialNumber}. The PREVIOUS key still works until you "
                  + "retire it, so a staggered firmware rollout will not lock a unit out. "
                  + "Copy it now — it cannot be shown again.";

        await LoadAsync(me.EventId, ct);
        return Page();
    }

    /// <summary>
    /// §1259 — issue a ONE-TIME pairing code so an iPad running <c>/eval</c> can become this
    /// device. The kiosk is an option ON the device model, not a separate system: same identifier,
    /// same key, same room link, same ingest contract, same reports.
    /// </summary>
    /// <remarks>
    /// 🔑 A code rather than the key itself, because the key is 43 characters and the thing typing
    /// it is a tablet keyboard held by someone standing in a corridor. The code is short, single
    /// use, and expires within the hour; redeeming it rotates the device's key, so a lost iPad is
    /// revoked by pairing its replacement.
    /// </remarks>
    public async Task<IActionResult> OnPostPairAsync(int id, CancellationToken ct)
    {
        var me = _participant.Current;
        if (me is null) return RedirectToPage("/Login");
        if (!OrganizerAuth.IsRealOrganizer(me)) return Forbid();

        var device = await _db.EvaluationDevices
            .FirstOrDefaultAsync(d => d.Id == id && d.EventId == me.EventId, ct);
        if (device is null) { Message = "That device no longer exists."; await LoadAsync(me.EventId, ct); return Page(); }

        var issued = await _kiosk.IssuePairingCodeAsync(device.Id, ct);
        if (issued is null) { Message = "Could not issue a pairing code."; await LoadAsync(me.EventId, ct); return Page(); }

        PairingCode = issued.Code;
        PairingCodeFor = device.SerialNumber;
        PairingCodeExpiresAt = issued.ExpiresAt;
        Message = $"Pairing code for {device.SerialNumber}. On the kiosk device open /eval, tap the "
                  + "top-left corner five times, and type this code. It works once and expires "
                  + $"{EvaluationKioskService.PairingWindow.TotalMinutes:0} minutes from now.";

        await LoadAsync(me.EventId, ct);
        return Page();
    }

    /// <summary>
    /// §1259c — issue this kiosk's ENROLMENT LINK: one URL the iPad keeps on its Home Screen that
    /// makes it this device again whenever the browser has forgotten — after a storage eviction, a
    /// wipe, or on a replacement tablet. This is what removes any daily login across 20 iPads.
    /// </summary>
    /// <remarks>
    /// ⚠️ The link contains a secret, which is a deliberate exception to "never a credential in a
    /// URL". It grants exactly one capability — to be this kiosk, whose only power is adding
    /// ratings to its room — and re-issuing revokes the previous link. The alternative is a human
    /// typing codes on 20 tablets mid-event, which is the failure this is avoiding.
    /// </remarks>
    public async Task<IActionResult> OnPostEnrolLinkAsync(int id, CancellationToken ct)
    {
        var me = _participant.Current;
        if (me is null) return RedirectToPage("/Login");
        if (!OrganizerAuth.IsRealOrganizer(me)) return Forbid();

        var device = await _db.EvaluationDevices
            .FirstOrDefaultAsync(d => d.Id == id && d.EventId == me.EventId, ct);
        if (device is null) { Message = "That device no longer exists."; await LoadAsync(me.EventId, ct); return Page(); }

        var token = await _kiosk.IssueEnrolmentTokenAsync(device.Id, ct);
        if (token is null) { Message = "Could not issue an enrolment link."; await LoadAsync(me.EventId, ct); return Page(); }

        EnrolmentLink = $"{Request.Scheme}://{Request.Host}/eval?k={Uri.EscapeDataString(token)}";
        EnrolmentLinkFor = device.SerialNumber;
        Message = $"Enrolment link for {device.SerialNumber}. Open it once on that kiosk device and keep it "
                  + "as its start page — it re-connects itself from then on. Any previous link for "
                  + "this device has stopped working.";

        await LoadAsync(me.EventId, ct);
        return Page();
    }

    /// <summary>§1259c — stop a kiosk re-enrolling (a lost or stolen iPad).</summary>
