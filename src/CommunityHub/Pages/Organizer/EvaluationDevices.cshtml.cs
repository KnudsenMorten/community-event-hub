    public async Task<IActionResult> OnPostApproveAsync(int id, CancellationToken ct)
    {
        var me = _participant.Current;
        if (me is null) return RedirectToPage("/Login");
        if (!OrganizerAuth.IsRealOrganizer(me)) { AccessDenied = true; return Page(); }

        var ok = await _provisioning.ApproveAsync(id, me.Email ?? "organizer", ct);
        // 🔑 Say what happens NEXT, not just that it worked. The device is not live yet — it collects
        // its key on its next poll, up to an hour away — and an organizer expecting an instant green
        // light will otherwise think the approval failed.
        Message = ok
            ? "Approved. The unit collects its key on its next check-in (up to an hour) and appears "
              + "in the device list above once it does."
            : "That request was already approved.";

        await LoadAsync(me.EventId, ct);
        return Page();
    }

    public async Task<IActionResult> OnPostRejectAsync(int id, CancellationToken ct)
    {
        var me = _participant.Current;
        if (me is null) return RedirectToPage("/Login");
        if (!OrganizerAuth.IsRealOrganizer(me)) { AccessDenied = true; return Page(); }

        var ok = await _provisioning.RejectAsync(id, me.Email ?? "organizer", ct);
        Message = ok
            ? "Refused. If a device row had already been created for it, that row is now revoked too."
            : "Request not found.";

        await LoadAsync(me.EventId, ct);
        return Page();
    }

    /// <summary>Add one FROM/TO line to the telemetry schedule, entered in Copenhagen time.</summary>
    public async Task<IActionResult> OnPostAddWindowAsync(
        DateTime from, DateTime to, string? label, CancellationToken ct)
    {
        var me = _participant.Current;
        if (me is null) return RedirectToPage("/Login");
        if (!OrganizerAuth.IsRealOrganizer(me)) { AccessDenied = true; return Page(); }

        if (to <= from)
        {
            Message = "The end of a window must be after its start.";
            await LoadAsync(me.EventId, ct);
            return Page();
        }

        // 🔒 The typed value is Copenhagen wall-clock. Convert with the ZONE, never by adding a fixed
        // offset — Denmark is UTC+1 in February and UTC+2 in summer, and a hard-coded +1 would
        // silently shift every window added between March and October by an hour.
        var now = _clock.GetUtcNow();
        _db.EvaluationTelemetryWindows.Add(new EvaluationTelemetryWindow
        {
            EventId = me.EventId,
            FromUtc = new DateTimeOffset(from, EventZone.GetUtcOffset(from)).ToUniversalTime(),
            ToUtc = new DateTimeOffset(to, EventZone.GetUtcOffset(to)).ToUniversalTime(),
            Label = string.IsNullOrWhiteSpace(label) ? null : label.Trim(),
            IsActive = true,
            CreatedAt = now,
            UpdatedAt = now,
        });
        await _db.SaveChangesAsync(ct);

        Message = "Window added.";
        await LoadAsync(me.EventId, ct);
        return Page();
    }

    public async Task<IActionResult> OnPostToggleWindowAsync(int id, CancellationToken ct)
    {
        var me = _participant.Current;
        if (me is null) return RedirectToPage("/Login");
        if (!OrganizerAuth.IsRealOrganizer(me)) { AccessDenied = true; return Page(); }

        var w = await _db.EvaluationTelemetryWindows
            .FirstOrDefaultAsync(x => x.Id == id && x.EventId == me.EventId, ct);
        if (w is not null)
        {
            w.IsActive = !w.IsActive;
            w.UpdatedAt = _clock.GetUtcNow();
            await _db.SaveChangesAsync(ct);
            Message = w.IsActive ? "Window enabled." : "Window parked.";
        }

        await LoadAsync(me.EventId, ct);
        return Page();
    }

    /// <summary>The per-device HARD switch. 🔒 Beats the schedule in both directions.</summary>
    public async Task<IActionResult> OnPostToggleDeviceHealthAsync(int id, CancellationToken ct)
    {
        var me = _participant.Current;
        if (me is null) return RedirectToPage("/Login");
        if (!OrganizerAuth.IsRealOrganizer(me)) { AccessDenied = true; return Page(); }

        var d = await _db.EvaluationDevices
            .FirstOrDefaultAsync(x => x.Id == id && x.EventId == me.EventId, ct);
        if (d is not null)
        {
            d.HealthTelemetryEnabled = !d.HealthTelemetryEnabled;
            d.UpdatedAt = _clock.GetUtcNow();
            await _db.SaveChangesAsync(ct);
            Message = d.HealthTelemetryEnabled
                ? "Health telemetry allowed for that unit (the schedule still applies)."
                : "Health telemetry HARD-disabled for that unit — no schedule can re-enable it.";
        }

        await LoadAsync(me.EventId, ct);
        return Page();
    }

    private async Task LoadOnboardingAsync(int eventId, CancellationToken ct)
    {
        Pending = await _db.EvaluationDeviceProvisionRequests
            .Where(r => r.EventId == eventId && r.Status == EvaluationProvisionStatus.Pending)
            .OrderByDescending(r => r.LastRequestedAt)
            .ToListAsync(ct);

        Windows = await _db.EvaluationTelemetryWindows
            .Where(w => w.EventId == eventId)
            .OrderBy(w => w.FromUtc)
            .ToListAsync(ct);

        // 🔑 The SAME policy the API answers with — never a second copy of the rule. A screen that
        // computes "on" its own way is how a GUI ends up reporting a state the fleet does not have.
        TelemetryRows = Devices.Select(d =>
        {
            var decision = EvaluationTelemetryPolicy.Evaluate(d, Windows, Now);
            return new TelemetryRow(d, decision.Enabled, decision.Why switch
            {
                EvaluationTelemetryPolicy.Reason.Enabled => "sending",
                EvaluationTelemetryPolicy.Reason.DeviceInactive => "device revoked",
                EvaluationTelemetryPolicy.Reason.HardDisabled => "hard-disabled",
                _ => "outside the schedule",
            });
        }).ToList();

        // Fleet-level answer, using a notional always-allowed device so the banner reflects the
        // SCHEDULE rather than any one unit's hard switch.
        var probe = new EvaluationDevice { Id = 0, IsActive = true, HealthTelemetryEnabled = true };
        var fleet = EvaluationTelemetryPolicy.Evaluate(
            probe, Windows.Where(w => w.EvaluationDeviceId is null), Now);
        TelemetryOffNow = !fleet.Enabled;
        TelemetryNextOn = fleet.NextOnAt;

        var secret = HttpContext.RequestServices.GetService<IConfiguration>()?
            [CommunityHub.Api.EvaluationProvisionController.SecretConfigKey];
        ProvisioningUnconfigured = string.IsNullOrWhiteSpace(secret);
    }

