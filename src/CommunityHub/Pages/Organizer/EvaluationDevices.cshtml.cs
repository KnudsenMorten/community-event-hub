    private async Task LoadOnboardingAsync(int eventId, CancellationToken ct)
    {
        Pending = await _db.EvaluationDeviceProvisionRequests
            .Where(r => r.EventId == eventId && r.Status == EvaluationProvisionStatus.Pending)
            .OrderByDescending(r => r.LastRequestedAt)
            .ToListAsync(ct);

        Windows = await _db.EvaluationTelemetryWindows
            .Where(w => w.EventId == eventId)
            .OrderBy(w => w.FromUtc)
            .ToListAsync(ct);

        // 🔑 The SAME policy the API answers with — never a second copy of the rule. A screen that
        // computes "on" its own way is how a GUI ends up reporting a state the fleet does not have.
        TelemetryRows = Devices.Select(d =>
        {
            var decision = EvaluationTelemetryPolicy.Evaluate(d, Windows, Now);
            return new TelemetryRow(d, decision.Enabled, decision.Why switch
            {
                EvaluationTelemetryPolicy.Reason.Enabled => "sending",
                EvaluationTelemetryPolicy.Reason.DeviceInactive => "device revoked",
                EvaluationTelemetryPolicy.Reason.HardDisabled => "hard-disabled",
                _ => "outside the schedule",
            });
        }).ToList();

        // Fleet-level answer, using a notional always-allowed device so the banner reflects the
        // SCHEDULE rather than any one unit's hard switch.
        var probe = new EvaluationDevice { Id = 0, IsActive = true, HealthTelemetryEnabled = true };
        var fleet = EvaluationTelemetryPolicy.Evaluate(
            probe, Windows.Where(w => w.EvaluationDeviceId is null), Now);
        TelemetryOffNow = !fleet.Enabled;
        TelemetryNextOn = fleet.NextOnAt;

        var secret = HttpContext.RequestServices.GetService<IConfiguration>()?
            [CommunityHub.Api.EvaluationProvisionController.SecretConfigKey];
        ProvisioningUnconfigured = string.IsNullOrWhiteSpace(secret);
    }

