    /// <summary>Presses that matched no session window — the early warning for clock drift.</summary>
    public IReadOnlyDictionary<string, int> UnattributedCounts { get; private set; }
        = new Dictionary<string, int>();

    /// <summary>Responses stored per device — the "is it actually collecting?" column.</summary>
    public IReadOnlyDictionary<string, int> ResponseCounts { get; private set; }
        = new Dictionary<string, int>();

    /// <summary>
    /// online / late / silent from last-seen — never from a connection, because these units sleep.
    /// </summary>
    public string StatusOf(EvaluationDevice d)
    {
        if (d.LastSeenAt is not DateTimeOffset seen) return "never seen";
        var age = Now - seen;
        if (age < TimeSpan.FromMinutes(30)) return "online";
        if (age < TimeSpan.FromHours(2)) return "late";
        return "silent";
    }
