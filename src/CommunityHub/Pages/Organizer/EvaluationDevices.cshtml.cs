    /// <summary>Add one FROM/TO line to the telemetry schedule, entered in Copenhagen time.</summary>
    public async Task<IActionResult> OnPostAddWindowAsync(
        DateTime from, DateTime to, string? label, CancellationToken ct)
    {
        var me = _participant.Current;
        if (me is null) return RedirectToPage("/Login");
        if (!OrganizerAuth.IsRealOrganizer(me)) { AccessDenied = true; return Page(); }

        if (to <= from)
        {
            Message = "The end of a window must be after its start.";
            await LoadAsync(me.EventId, ct);
            return Page();
        }

        // 🔒 The typed value is Copenhagen wall-clock. Convert with the ZONE, never by adding a fixed
        // offset — Denmark is UTC+1 in February and UTC+2 in summer, and a hard-coded +1 would
        // silently shift every window added between March and October by an hour.
        var now = _clock.GetUtcNow();
        _db.EvaluationTelemetryWindows.Add(new EvaluationTelemetryWindow
        {
            EventId = me.EventId,
            FromUtc = new DateTimeOffset(from, EventZone.GetUtcOffset(from)).ToUniversalTime(),
            ToUtc = new DateTimeOffset(to, EventZone.GetUtcOffset(to)).ToUniversalTime(),
            Label = string.IsNullOrWhiteSpace(label) ? null : label.Trim(),
            IsActive = true,
            CreatedAt = now,
            UpdatedAt = now,
        });
        await _db.SaveChangesAsync(ct);

        Message = "Window added.";
        await LoadAsync(me.EventId, ct);
        return Page();
    }

