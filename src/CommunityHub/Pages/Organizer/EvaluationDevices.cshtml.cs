        return Page();
    }

    /// <summary>
    /// §743 C2 — put a unit in a room. 🔑 The link is to the ROOM, never a session: a session moving
    /// to another room then re-points at that room's device automatically, and nobody has to touch
    /// hardware because a schedule changed.
    /// </summary>
    /// <remarks>
    /// Changing this does NOT re-attribute presses already collected. Responses attach to the
    /// session that was running when they were pressed, and rewriting history because a unit was
    /// carried to another room would move real feedback between speakers.
    /// </remarks>
    public async Task<IActionResult> OnPostSetRoomAsync(int id, int? roomId, CancellationToken ct)
    {
        var me = _participant.Current;
        if (me is null) return RedirectToPage("/Login");
        if (!OrganizerAuth.IsRealOrganizer(me)) return Forbid();

        var device = await _db.EvaluationDevices
            .FirstOrDefaultAsync(d => d.Id == id && d.EventId == me.EventId, ct);
        if (device is not null)
        {
            device.RoomId = roomId;
            device.UpdatedAt = _clock.GetUtcNow();
            await _db.SaveChangesAsync(ct);

            var roomName = roomId is null
                ? null
                : (await _db.EvaluationRooms.FirstOrDefaultAsync(r => r.Id == roomId, ct))?.Name;
            Message = roomId is null
                ? $"{DisplayName(device)} unlinked — its presses can no longer be attributed to a session."
                : $"{DisplayName(device)} is now in {roomName}.";
        }

        await LoadAsync(me.EventId, ct);
        return Page();
    }

