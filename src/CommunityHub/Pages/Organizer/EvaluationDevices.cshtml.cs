    private async Task LoadAsync(int eventId, CancellationToken ct)
    {
        Now = _clock.GetUtcNow();

        // §1259d — the kiosk URL and its QR, so a tablet can reach the page with its camera and a
        // laptop can simply be told the address. Best-effort: a QR failure must never take the
        // device board down with it.
        KioskUrl = $"{Request.Scheme}://{Request.Host}/eval";
        try
        {
            KioskQrDataUri = "data:image/png;base64,"
                + Convert.ToBase64String(EvaluationKioskService.RenderQrPng(KioskUrl, pixelsPerModule: 6));
        }
        catch { KioskQrDataUri = null; }
        Devices = await _db.EvaluationDevices
            .Where(d => d.EventId == eventId)
            .OrderBy(d => d.SerialNumber)
            .ToListAsync(ct);

        ResponseCounts = await _db.EvaluationResponses
            .Where(r => r.EventId == eventId && r.SerialNumber != null)
            .GroupBy(r => r.SerialNumber!)
            .Select(g => new { SerialNumber = g.Key, Count = g.Count() })
            .ToDictionaryAsync(x => x.SerialNumber, x => x.Count, ct);

        Rooms = await _db.EvaluationRooms
            .Where(r => r.EventId == eventId)
            .OrderBy(r => r.Name)
            .ToListAsync(ct);

        var defaults = await _db.Events.Where(e => e.Id == eventId)
            .Select(e => new { e.KioskCapturePolicy, e.QrCapturePolicy, e.KioskRatingSymbols, e.QrRatingSymbols }).FirstOrDefaultAsync(ct);
        DefaultKioskPolicy = FeedbackCapturePolicies.ForKiosk(defaults?.KioskCapturePolicy ?? FeedbackCapturePolicies.DefaultKiosk);
        DefaultQrPolicy = defaults?.QrCapturePolicy ?? FeedbackCapturePolicies.DefaultQr;
        DefaultKioskSymbols = defaults?.KioskRatingSymbols is { } ks && RatingSymbolChoices.IsValid((int)ks) ? ks : RatingSymbolChoices.Default;
        DefaultQrSymbols = defaults?.QrRatingSymbols is { } qs && RatingSymbolChoices.IsValid((int)qs) ? qs : RatingSymbolChoices.Default;

        // §1350 — physical rooms, what they hold, and the mapping's gaps.
        PhysicalRooms = await _db.EvaluationPhysicalRooms
            .Where(r => r.EventId == eventId)
            .Include(r => r.Placements)
            .OrderBy(r => r.Name)
            .ToListAsync(ct);
        MapWarnings = await EvaluationRoomMap.WarningsAsync(_db, eventId, ct);

        // §5.3 — presses this device collected that landed in NO session window. Surfaced per
        // device because a rising count is the earliest signal of a drifted clock or a schedule
        // that no longer matches reality, and if nobody can see it both stay silent until the
        // reports come out wrong.
        UnattributedCounts = await _db.EvaluationResponses
            .Where(r => r.EventId == eventId && r.SerialNumber != null && r.SessionId == null)
            .GroupBy(r => r.SerialNumber!)
            .Select(g => new { SerialNumber = g.Key, Count = g.Count() })
            .ToDictionaryAsync(x => x.SerialNumber, x => x.Count, ct);

        await LoadOnboardingAsync(eventId, ct);
    }

