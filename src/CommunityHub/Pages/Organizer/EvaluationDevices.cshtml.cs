    /// <summary>§1350 — a new physical room. Names are unique per event (trimmed, case-insensitive).</summary>
    public async Task<IActionResult> OnPostAddPhysicalRoomAsync(string? name, CancellationToken ct)
    {
        var me = _participant.Current;
        if (me is null) return RedirectToPage("/Login");
        if (!OrganizerAuth.IsRealOrganizer(me)) return Forbid();

        var clean = name?.Trim();
        if (string.IsNullOrEmpty(clean))
            Message = "Give the physical room a name.";
        else if (await PhysicalNameTakenAsync(me.EventId, clean, exceptId: null, ct))
            Message = $"A physical room called {clean} already exists.";
        else
        {
            _db.EvaluationPhysicalRooms.Add(new EvaluationPhysicalRoom
            {
                EventId = me.EventId, Name = clean, CreatedAt = _clock.GetUtcNow(),
            });
            await _db.SaveChangesAsync(ct);
            Message = $"Physical room {clean} added — tick the schedule rooms held there.";
        }

        await LoadAsync(me.EventId, ct);
        return Page();
    }

    /// <summary>
    /// §1350 — rename a physical room and REPLACE the schedule rooms it holds. Only this event's rooms
    /// are accepted; an id from elsewhere is ignored rather than linked.
    /// </summary>
    public async Task<IActionResult> OnPostSavePhysicalRoomAsync(int id, string? name, int[]? roomIds, CancellationToken ct)
    {
        var me = _participant.Current;
        if (me is null) return RedirectToPage("/Login");
        if (!OrganizerAuth.IsRealOrganizer(me)) return Forbid();

        var room = await _db.EvaluationPhysicalRooms
            .Include(r => r.Placements)
            .FirstOrDefaultAsync(r => r.Id == id && r.EventId == me.EventId, ct);
        if (room is not null)
        {
            var clean = name?.Trim();
            if (!string.IsNullOrEmpty(clean) && clean != room.Name)
            {
                if (await PhysicalNameTakenAsync(me.EventId, clean, exceptId: room.Id, ct))
                {
                    Message = $"A physical room called {clean} already exists.";
                    await LoadAsync(me.EventId, ct);
                    return Page();
                }
                room.Name = clean;
            }

            var requested = (roomIds ?? Array.Empty<int>()).Distinct().ToList();
            var valid = await _db.EvaluationRooms
                .Where(r => r.EventId == me.EventId && requested.Contains(r.Id))
                .Select(r => r.Id)
                .ToListAsync(ct);
            _db.EvaluationRoomPlacements.RemoveRange(room.Placements.Where(p => !valid.Contains(p.EvaluationRoomId)));
            foreach (var rid in valid.Where(v => room.Placements.All(p => p.EvaluationRoomId != v)))
                _db.EvaluationRoomPlacements.Add(new EvaluationRoomPlacement { PhysicalRoomId = room.Id, EvaluationRoomId = rid });
            await _db.SaveChangesAsync(ct);
            Message = $"{room.Name} holds {valid.Count} schedule room(s).";
        }

        await LoadAsync(me.EventId, ct);
        return Page();
    }

