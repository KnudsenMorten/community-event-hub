    /// <summary>
    /// §1266 — the most recent sign of life. A kiosk reports twice: the 5-minute heartbeat
    /// (<see cref="EvaluationDevice.LastSeenAt"/>) and the 60-second session refresh
    /// (<see cref="EvaluationDevice.KioskLastSeenAt"/>). Status read only the first, so an open
    /// iPad could show "late" while it was asking the server every minute.
    /// </summary>
    public static DateTimeOffset? LastContact(EvaluationDevice d) =>
        (d.LastSeenAt, d.KioskLastSeenAt) switch
        {
            (DateTimeOffset a, DateTimeOffset b) => a > b ? a : b,
            (DateTimeOffset a, null) => a,
            (null, DateTimeOffset b) => b,
            _ => null,
        };

    public string StatusOf(EvaluationDevice d)
    {
        if (LastContact(d) is not DateTimeOffset seen) return "never seen";
        var age = Now - seen;
        if (age < TimeSpan.FromMinutes(30)) return "online";
        if (age < TimeSpan.FromHours(2)) return "late";
        return "silent";
    }
